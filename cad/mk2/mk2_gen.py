"""Generate cad/mk2/mk2_parts.scad: every placed MK2-2020 mesh with the transform that moves it into our frame.

Usage: python mk2_gen.py <placed dir> <out .scad>
Each mesh is assigned a group; the group decides the translation (see GROUPS in the generated file).
Motors are not imported: we emit their face centre and shaft direction, and draw our own 47 mm NEMA17.
"""
import glob, os, re, sys

src, out = sys.argv[1], sys.argv[2]
SKIP = re.compile(r'SHCS|BHCS|WASHER|NUT_THIN|NUT_SQUARE|NUT_NYLOC|Perfil|LINEAR_ROD|belt|MK42|Z-SCREW-COVER|SPRING|PINDA')

def verts(f):
    return [tuple(map(float, m.groups())) for m in re.finditer(r'vertex\s+(\S+)\s+(\S+)\s+(\S+)', open(f).read())]

def motor_axis(vs):
    """Return (face centre, unit shaft direction) of a NEMA17 mesh: the back end is the 42.3 mm square."""
    lo = [min(v[a] for v in vs) for a in range(3)]; hi = [max(v[a] for v in vs) for a in range(3)]
    for a in range(3):
        o = [b for b in range(3) if b != a]
        for back, sgn in ((lo[a], 1), (hi[a], -1)):
            sl = [v for v in vs if abs(v[a] - back) < 0.5]
            if not all(abs(max(v[b] for v in sl) - min(v[b] for v in sl) - 42.3) < 0.5 for b in o):
                continue
            c = [(max(v[b] for v in sl) + min(v[b] for v in sl)) / 2 for b in range(3)]
            body = [v[a] for v in vs if min(abs(v[b] - c[b]) for b in o) > 15]
            c[a] = max(body) if sgn > 0 else min(body)
            d = [0, 0, 0]; d[a] = sgn
            return [round(x, 2) for x in c], d
    raise ValueError('no motor axis found')

rows = []
for f in sorted(glob.glob(os.path.join(src, '*.stl'))):
    name = os.path.basename(f)[:-4]
    if SKIP.search(name):
        continue
    vs = verts(f)
    lo = [min(v[a] for v in vs) for a in range(3)]; hi = [max(v[a] for v in vs) for a in range(3)]
    c = [(lo[a] + hi[a]) / 2 for a in range(3)]
    size = [hi[a] - lo[a] for a in range(3)]
    side = 'L' if c[0] < -100 else 'R' if c[0] > 100 else 'C'
    # brace rods and their joints: we keep our 2020 braces
    ss = sorted(size)
    near = lambda ref: all(abs(a - b) < 2 for a, b in zip(ss, ref))
    if name.startswith(('Part_1', 'Assembly_2')) and (ss[2] > 150 or near([14, 25.2, 37.1]) or near([20, 20, 20])):
        continue
    if 'NEMA17' in name:
        fc, d = motor_axis(vs)
        grp = ('zb' if 'Z_AXIS' in name else 'xe' if 'X_AXIS' in name else 'yr' if 'Y_AXIS' in name else 'xc')
        rows.append(('motor', name, grp, side, fc, d)); continue
    if name.startswith('Part_1') and near([25, 60, 80]):                    # upright-to-base adapters
        grp = 'adapter'
    elif lo[2] < -230 or (name.startswith('Part_1') and hi[2] < -190) or 'Y-MOTOR-HOLDER' in name or name == 'Part6_1':
        # feet, base corner blocks, and the Y motor holder / Y idler (Part6) clamped on the base bars
        grp = 'base_front' if c[1] < 261 else 'base_rear'
    elif name.startswith('Part_1') and hi[2] > 130:                          # top gussets, top corner blocks
        grp = 'top'
    elif name.startswith('Part_1'):                                          # upright-to-base adapters
        grp = 'adapter'
    elif 'Z-AXIS-TOP' in name:
        grp = 'top'
    elif 'Z-AXIS-BOTTOM' in name:
        grp = 'zb'
    elif side != 'C' and lo[2] > -60:                                        # X-ends, X motor/idler, Z nuts, X-end bearings
        grp = 'xe'
    elif side == 'C' and lo[2] > -60:                                        # carriage, extruder, fans, X carriage bearings
        grp = 'xc'
    elif re.search(r'CARRIAGE|y_bearing|BELT-HOLDER|CABLE_COVER|Y_AXIS_ASM_1___LM8UU', name):
        grp = 'bed'
    elif c[1] < 261:
        grp = 'y_front'
    else:
        grp = 'y_rear'
    rows.append(('mesh', name, grp, side, [round(x, 2) for x in lo], [round(x, 2) for x in hi]))

with open(out, 'w') as o:
    o.write('// Generated by mk2_gen.py from the MK2-2020 GrabCAD assembly. Do not edit by hand.\n')
    o.write('// [kind, file, group, side, a, b]: mesh -> a/b = bbox min/max (MK2 coordinates);\n')
    o.write('//                                  motor -> a = face centre, b = shaft direction.\n')
    o.write('mk2_items = [\n')
    for r in rows:
        o.write(f'    ["{r[0]}", "{r[1]}", "{r[2]}", "{r[3]}", {list(r[4])}, {list(r[5])}],\n')
    o.write('];\n')
for r in rows:
    print(r[0], r[2], r[3], r[1][-45:], r[4], r[5])
